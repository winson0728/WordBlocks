import 'dart:convert';

import 'package:flutter/services.dart' show rootBundle;

/// Prefix, root or suffix. [link] marks letters the splitter could not match.
enum MorphemeType { pre, root, suf, link }

const typeNames = {
  MorphemeType.pre: '字首',
  MorphemeType.root: '字根',
  MorphemeType.suf: '字尾',
  MorphemeType.link: '連接',
};

const typeTags = {
  MorphemeType.pre: 'PREFIX',
  MorphemeType.root: 'ROOT',
  MorphemeType.suf: 'SUFFIX',
  MorphemeType.link: 'LINK',
};

class Category {
  const Category(this.id, this.name);
  final String id;
  final String name;
}

class Morpheme {
  const Morpheme({
    required this.id,
    required this.type,
    required this.forms,
    required this.meaning,
    required this.origin,
    required this.category,
    this.story,
    this.scene,
  });

  factory Morpheme.fromJson(Map<String, dynamic> j) => Morpheme(
        id: j['id'] as String,
        type: MorphemeType.values.byName(j['type'] as String),
        forms: j['forms'] as String,
        meaning: j['meaning'] as String,
        origin: j['origin'] as String,
        category: j['category'] as String,
        story: j['story'] as String?,
        scene: j['scene'] as String?,
      );

  final String id;
  final MorphemeType type;

  /// Display string such as "sub- / sup- / su-".
  final String forms;
  final String meaning;
  final String origin;
  final String category;
  final String? story;
  final String? scene;

  static final _note = RegExp(r'（.*）');

  /// First form, e.g. "sub-".
  String get label => forms.split(' / ').first.replaceAll(_note, '');

  /// First sense of the meaning, e.g. "在下" from "在下、從下".
  String get shortMeaning => meaning.split(RegExp(r'[、；（]')).first;

  /// Lower-case spellings without hyphens, used by the splitter.
  List<String> get spellings => forms
      .replaceAll(_note, '')
      .split(' / ')
      .map((f) => f.toLowerCase().replaceAll(RegExp('[^a-z]'), ''))
      .where((s) => s.isNotEmpty)
      .toList();
}

class WordPart {
  const WordPart(this.id, this.text);

  /// Morpheme id, or null for unmatched letters.
  final String? id;
  final String text;
}

const levelNames = {1: '基礎', 2: '進階', 3: '高階'};

class Word {
  const Word({
    required this.word,
    required this.parts,
    required this.meaning,
    required this.literal,
    required this.example,
    this.level = 2,
  });

  factory Word.fromJson(Map<String, dynamic> j) => Word(
        word: j['word'] as String,
        parts: [
          for (final p in j['parts'] as List)
            WordPart(p['id'] as String, p['text'] as String),
        ],
        meaning: j['meaning'] as String,
        literal: j['literal'] as String,
        example: j['example'] as String,
        level: (j['level'] as num?)?.toInt() ?? 2,
      );

  final String word;
  final List<WordPart> parts;
  final String meaning;
  final String literal;
  final String example;

  /// 1 基礎, 2 進階, 3 高階, from how common the word is (tools/assign_levels.py).
  final int level;

  String get shortMeaning => meaning.split('；').first;
}

/// All WordBlocks data, loaded from assets/wordblocks.json.
/// That file is generated by tools/build-data.mjs from data/*.txt, the same
/// source the web app uses.
class Lexicon {
  Lexicon({required this.categories, required List<Morpheme> morphemes, required this.words})
      : morphemes = {for (final m in morphemes) m.id: m},
        byWord = {for (final w in words) w.word: w} {
    for (final w in words) {
      for (final p in w.parts) {
        final list = _byMorpheme.putIfAbsent(p.id!, () => []);
        if (!list.contains(w)) list.add(w);
      }
    }
  }

  factory Lexicon.fromJson(Map<String, dynamic> j) => Lexicon(
        categories: [
          for (final c in j['categories'] as List) Category(c['id'] as String, c['name'] as String),
        ],
        morphemes: [for (final m in j['morphemes'] as List) Morpheme.fromJson(m as Map<String, dynamic>)],
        words: [for (final w in j['words'] as List) Word.fromJson(w as Map<String, dynamic>)],
      );

  static Future<Lexicon> load() async =>
      Lexicon.fromJson(jsonDecode(await rootBundle.loadString('assets/wordblocks.json', cache: false)) as Map<String, dynamic>);

  final List<Category> categories;
  final Map<String, Morpheme> morphemes;
  final List<Word> words;
  final Map<String, Word> byWord;
  final Map<String, List<Word>> _byMorpheme = {};

  /// Words built on [morphemeId], optionally only those at or below [maxLevel].
  List<Word> wordsWith(String morphemeId, {int maxLevel = 3}) {
    final all = _byMorpheme[morphemeId] ?? const <Word>[];
    return maxLevel >= 3 ? all : [for (final w in all) if (w.level <= maxLevel) w];
  }

  String categoryName(String id) =>
      categories.firstWhere((c) => c.id == id, orElse: () => Category(id, id)).name;

  final Map<int, List<String>> _decks = {};

  /// Prefixes and roots with at least one word at or below [maxLevel]: the review deck.
  List<String> deckFor(int maxLevel) => _decks.putIfAbsent(maxLevel, () => [
        for (final m in morphemes.values)
          if (m.type != MorphemeType.suf && wordsWith(m.id, maxLevel: maxLevel).isNotEmpty) m.id,
      ]);

  /// Roots with at least three words, in a fixed order. "Root of the day" cycles through this
  /// list; the Android home-screen widget receives the same list and must pick the same item.
  late final List<Morpheme> dailyRoots = [
    for (final m in morphemes.values)
      if (m.type == MorphemeType.root && wordsWith(m.id).length >= 3) m,
  ];

  /// Days since 2024-01-01 for the local calendar date. Uses UTC dates so daylight-saving
  /// changes never shift the count; TodayRootWidget.kt computes the same number.
  static int dayNumber(DateTime now) =>
      DateTime.utc(now.year, now.month, now.day).difference(DateTime.utc(2024)).inDays;

  /// A root that changes once a day, for the "today's root" card and the home-screen widget.
  Morpheme rootOfTheDay(DateTime now) => dailyRoots[dayNumber(now) % dailyRoots.length];

}
