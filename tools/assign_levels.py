#!/usr/bin/env python3
"""Assign a difficulty level to every word in data/words.txt, from how common it is in English.

  1 基礎  zipf >= 4.0   (transport, nation, apply)
  2 進階  zipf >= 3.3   (construct, inspect, procurement)
  3 高階  below 3.3     (premonition, synchronize)

Writes data/levels.txt (word|level). To pin a level by hand, add the word to data/level-overrides.txt
in the same word|level format; overrides win over the computed level.

Frequencies come from the `wordfreq` package (data CC BY-SA 4.0, by Robyn Speer and contributors):
pip install wordfreq
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANDS = [(4.0, 1), (3.3, 2)]


def level_for(zipf):
    for cut, lv in BANDS:
        if zipf >= cut:
            return lv
    return 3


def main():
    from wordfreq import zipf_frequency

    words = [l.split("|")[0].strip() for l in (ROOT / "data/words.txt").read_text(encoding="utf-8").splitlines()
             if l.strip() and not l.startswith("#")]
    overrides = {}
    path = ROOT / "data/level-overrides.txt"
    if path.exists():
        for l in path.read_text(encoding="utf-8").splitlines():
            if l.strip() and not l.startswith("#"):
                w, lv = l.split("|")
                overrides[w.strip()] = int(lv)
    out = ["# Generated by tools/assign_levels.py from word frequency (wordfreq, CC BY-SA 4.0). 1 基礎, 2 進階, 3 高階."]
    counts = {1: 0, 2: 0, 3: 0}
    for w in words:
        lv = overrides.get(w) or level_for(zipf_frequency(w, "en"))
        counts[lv] += 1
        out.append(f"{w}|{lv}")
    (ROOT / "data/levels.txt").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Levels: {counts[1]} 基礎, {counts[2]} 進階, {counts[3]} 高階 -> data/levels.txt")


if __name__ == "__main__":
    main()
